function zDetect() {
  try {
    const s = ZI18N_STORE.get();
    if (s && Z_LOCALES[s]) return s;
  } catch (_) {}
  try {
    const n = (navigator.language || "en").toLowerCase();
    if (n.startsWith("fa")) return "fa";
    if (n.startsWith("zh")) return "zh";
    if (n.startsWith("ru")) return "ru";
  } catch (_) {}
  return "en";
}

let Z_LANG = "en";
const ZI18N_STORE = {
  key: "zefira_lang",
  get() { try { return localStorage.getItem(this.key); } catch (_) { return null; } },
  set(v) { try { localStorage.setItem(this.key, v); } catch (_) {} },
};

function t(key, vars) {
  const d = Z_STRINGS[Z_LANG] || {};
  let s = d[key] !== undefined ? d[key] : (Z_STRINGS.en[key] !== undefined ? Z_STRINGS.en[key] : key);
  if (vars) {
    for (const k of Object.keys(vars)) s = s.split("{" + k + "}").join(String(vars[k]));
  }
  return s;
}

function setLang(lang, store) {
  if (!Z_LOCALES[lang]) lang = "en";
  Z_LANG = lang;
  if (store) store.set(lang);
  try { document.cookie = "zefira_lang=" + lang + "; path=/; max-age=31536000; samesite=strict"; } catch (_) {}
  try {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : lang;
    document.documentElement.dir = Z_LOCALES[lang].dir;
  } catch (_) {}
  applyI18n(document);
  try { document.dispatchEvent(new CustomEvent("zefira-lang", { detail: lang })); } catch (_) {}
}

function applyI18n(root) {
  const q = (sel) => Array.from((root || document).querySelectorAll(sel));
  q("[data-i18n]").forEach((el) => { el.textContent = t(el.getAttribute("data-i18n")); });
  q("[data-i18n-ph]").forEach((el) => { el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph"))); });
  q("[data-i18n-title]").forEach((el) => { el.setAttribute("title", t(el.getAttribute("data-i18n-title"))); });
  q("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria"))); });
  q("[data-i18n-alt]").forEach((el) => { el.setAttribute("alt", t(el.getAttribute("data-i18n-alt"))); });
}

